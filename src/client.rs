    ///
    /// The same walk as [`Self::for_each_share`], with the same two refusals rather than a
    /// loop: an echoed page number that is not the one requested, and [`MAX_PAGES`] reached
    /// without the API ever signalling the end.
    pub fn for_each_request<F>(&self, limit: u32, mut visit: F) -> Result<()>
    where
        F: FnMut(&RequestSummary) -> Result<()>,
    {
        let limit = if limit == 0 { 100 } else { limit };
        let mut page = 1u32;
        loop {
            let batch = self.list_requests(limit, page)?;

            if batch.page != page {
                return Err(Error::Internal(
                    "the API echoed a different page number than the one requested, so paging \
                     cannot be trusted to terminate",
                ));
            }

            for request in &batch.requests {
                visit(request)?;
            }
            if !batch.has_more() {
                return Ok(());
            }
            if page >= MAX_PAGES {
                return Err(Error::InternalOwned(format!(
                    "stopped after {MAX_PAGES} pages without the API signalling the end of the \
                     result set; it sent neither total_pages nor total, and every page came \
                     back full"
                )));
            }
            page += 1;
        }
    }

