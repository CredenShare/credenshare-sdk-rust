    /// Assemble a collect link for a request's short code.
    ///
    /// `{link_origin}/r/{short_code}`, which is the path the app serves the collect form on.
    /// Unlike [`Self::link_for`] there is no fragment, because there is no key to put in one:
    /// this link is safe to publish, and holding it lets somebody submit rather than read.
    pub fn collect_link_for(&self, short_code: &str) -> String {
        format!("{}/r/{short_code}", self.options.link_origin)
    }

    /// Assemble YOUR access link for a request: the seed in the fragment.
    ///
    /// The other half of [`Self::collect_link_for`], and the opposite in every way that
    /// matters — treat the result as the secret itself, because it IS the ability to read
    /// every submission, on any device, with nothing stored. Browsers never send a fragment to
    /// a server, so the seed stays yours; CredenShare cannot rebuild this link, because the
    /// seed was never ours.
    ///
    /// The point of it is turning a seed you stored at create time back into something a
    /// person can open, which is also why hand-assembly is the wrong move: the fragment is
    /// version-prefixed (`"1" + base64url(seed)`) and a hand-built one without the prefix
    /// fails as a damaged link.
    ///
    /// A wrong-length seed is [`Error::MalformedKey`] here rather than an error from inside a
    /// crypto primitive, so the message names the argument the caller passed.
    pub fn access_link_for(&self, short_code: &str, seed: &[u8]) -> Result<String> {
        if seed.len() != crypto::SEED_LENGTH {
            return Err(Error::MalformedKey(format!(
                "a request seed is {} bytes; this one is {}",
                crypto::SEED_LENGTH,
                seed.len()
            )));
        }
        Ok(format!(
            "{}/r/{short_code}#{}",
            self.options.link_origin,
            crypto::encode_fragment(seed)?
        ))
    }

    /// Mint a keypair, create a secure request, and hand you the seed.
    ///
    /// The keypair is generated HERE. The API receives the public half; the 32-byte seed exists
    /// only in the returned [`SecureRequest`] and is never transmitted — which is the whole
    /// point of the endpoint rather than a detail of it. Submissions are sealed to the public
    /// key, so that seed is the only thing in the world able to read them.
    ///
    /// Store it before the returned value drops. A request whose seed is lost goes on
    /// collecting submissions that nobody, CredenShare included, can ever open — and there is
    /// no recovery path, by construction.
    ///
    /// Pass [`CreateRequestParams::seed`] to derive the keypair from a seed you already hold,
    /// which is what a runner deriving from its credential's custody secret wants.
    pub fn create_request(&self, params: CreateRequestParams) -> Result<SecureRequest> {
        check_request_fields(&params.fields)?;

        let seed = params.seed.unwrap_or_else(crypto::new_seed);
        let keypair = crypto::keypair_from_seed(&seed)?;

        let mut body = Map::new();
        body.insert("title".into(), json!(params.title));
        // UNPADDED base64url, which is the encoding the API's key validator accepts. The
        // submission blobs that come back later are padded STANDARD base64: the same feature,
        // two encodings, and feeding either decoder the other's output fails.
        body.insert("public_key".into(), json!(keypair.public_key_b64url()));
        body.insert(
            "fields".into(),
            Value::Array(
                params
                    .fields
                    .iter()
                    .map(|field| {
                        let mut prompt = Map::new();
                        prompt.insert("item".into(), json!(field.item));
                        // Omitted rather than sent empty, so the API's own default of `text`
                        // applies instead of a field with no renderer.
                        if !field.field_type.is_empty() {
                            prompt.insert("type".into(), json!(field.field_type));
                        }
                        Value::Object(prompt)
                    })
                    .collect(),
            ),
        );

        if let Some(description) = &params.description {
            body.insert("description".into(), json!(description));
        }
        if let Some(passcode) = &params.passcode {
            // Sent, unlike a share's. See CreateRequestParams::passcode: the server evaluates
            // this one to gate the form, and it opens nothing.
            body.insert("passcode".into(), json!(passcode));
        }
        if let Some(expired_at) = &params.expired_at {
            body.insert("expired_at".into(), json!(expired_at));
        }
        if let Some(count) = params.max_submission {
            body.insert("max_submission".into(), json!(count));
        }
        if let Some(count) = params.access_counts_left {
            body.insert("access_counts_left".into(), json!(count));
        }
        if let Some(flag) = params.requires_login {
            body.insert("requires_login".into(), json!(flag));
        }
        if let Some(flag) = params.requires_mfa {
            body.insert("requires_mfa".into(), json!(flag));
        }
        if !params.restricted_domain.is_empty() {
            body.insert("restricted_domain".into(), json!(params.restricted_domain));
        }
        if !params.ip_whitelist.is_empty() {
            body.insert("ip_whitelist".into(), json!(params.ip_whitelist));
        }
        if let Some(organization_id) = &params.organization_id {
            body.insert("organization_id".into(), json!(organization_id));
        }

        // Required by the API, as it is on a share, and for a sharper reason: a duplicate
        // collect link is not inert — a person can fill it in, and the submission lands
        // somewhere its owner never looks.
        let idempotency_key = params.idempotency_key.unwrap_or_else(random_token);

        // Belt and braces at the boundary, in the manner of the custody assertion in
        // [`Self::request`]. Asserted against the SERIALIZED body rather than against the
        // field list above, so a seed that arrived through a title, a description or a prompt
        // is caught too — and against the outgoing Idempotency-Key, because a caller deriving
        // a deterministic key from a deterministic seed has the seed in hand and that header
        // travels on the same request as the body.
        let body = Value::Object(body);
        let outgoing = format!("{body}{idempotency_key}");
        if seed_renderings(&seed)
            .iter()
            .any(|rendering| outgoing.contains(rendering.as_str()))
        {
            return Err(Error::RequestSeedTransmitted);
        }

        let data = self.request(
            "POST",
            "/requests",
            Some(body),
            &[],
            &[(IDEMPOTENCY_HEADER, idempotency_key.as_str())],
        )?;

        let short_code = data
            .get("short_code")
            .and_then(Value::as_str)
            .ok_or(Error::Internal("the API returned no short_code"))?
            .to_string();

        Ok(SecureRequest {
            collect_link: self.collect_link_for(&short_code),
            access_link: self.access_link_for(&short_code, &seed)?,
            short_code,
            // Echoed back by the API, and falling back to what was sent rather than to an
            // empty string: a caller comparing the two is checking exactly this.
            public_key: data
                .get("public_key")
                .and_then(Value::as_str)
                .map(str::to_string)
                .unwrap_or_else(|| keypair.public_key_b64url()),
            expired_at: data
                .get("expired_at")
                .and_then(Value::as_str)
                .map(str::to_string),
            seed: Zeroizing::new(seed),
        })
    }

