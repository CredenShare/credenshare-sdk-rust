    /// Every share, page by page, handed to `visit`.
    ///
    /// Written here because the hand-rolled version is usually wrong in the same way: it stops
    /// on the first page shorter than `limit`, which is a page the server is entitled to return
    /// in the middle of a result set.
    /// # Errors
    ///
    /// Beyond anything [`Self::list_shares`] can return, the walk itself refuses two things
    /// rather than looping:
    ///
    /// - the API echoing a page number other than the one requested, which makes progress
    ///   unobservable;
    /// - reaching [`MAX_PAGES`] without the API ever signalling the end of the result set.
    ///
    /// Both are [`Error::Internal`] / [`Error::InternalOwned`] and both are preferable to the
    /// alternative, which is a process that never returns.
    pub fn for_each_share<F>(&self, limit: u32, mut visit: F) -> Result<()>
    where
        F: FnMut(&ShareSummary) -> Result<()>,
    {
        let limit = if limit == 0 { 100 } else { limit };
        let mut page = 1u32;
        loop {
            let batch = self.list_shares(limit, page)?;

            // A server that echoes a constant page number makes progress unobservable, and
            // has_more's last-resort fallback (a full page probably has a successor) would
            // then loop forever on the same rows. Terminate loudly instead of hanging.
            if batch.page != page {
                return Err(Error::Internal(
                    "the API echoed a different page number than the one requested, so paging \
                     cannot be trusted to terminate",
                ));
            }

            for share in &batch.shares {
                visit(share)?;
            }
            if !batch.has_more() {
                return Ok(());
            }
            if page >= MAX_PAGES {
                return Err(Error::InternalOwned(format!(
                    "stopped after {MAX_PAGES} pages without the API signalling the end of the \
                     result set; it sent neither total_pages nor total, and every page came \
                     back full"
                )));
            }
            page += 1;
        }
    }

