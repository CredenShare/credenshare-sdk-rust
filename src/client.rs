/// The production API.
pub const DEFAULT_BASE_URL: &str = "https://api.credenshare.io/v1";
/// Where recipient links live.
pub const DEFAULT_LINK_ORIGIN: &str = "https://crs.sh";

/// The only accepted encryption type. Plaintext creates are refused by the server, and this
/// client has no way to express one.
const ENCRYPTION_TYPE: &str = "e2ee-aes256-gcm";

/// The API's numeric code for an exhausted plan allowance. Distinguished from other 403s
/// because waiting does not help and the remedy is a plan change, not a retry.
const QUOTA_EXCEEDED_CODE: i64 = 61;

/// The API's numeric code for an Idempotency-Key replayed with a different body.
const IDEMPOTENCY_CONFLICT_CODE: i64 = 105;

/// The header every `POST`, `PUT` and `PATCH` carries, generated by [`CredenShare::request`]
/// when the caller has not supplied one. See [`IDEMPOTENT_METHODS`] for why `DELETE` is not on
/// that list.
const IDEMPOTENCY_HEADER: &str = "Idempotency-Key";

/// The methods that get an automatic `Idempotency-Key`, and the reason the list is not simply
/// "everything but GET".
///
/// The API consults the header on CREATES. On a `DELETE` it is not read at all, so generating
/// one buys nothing — and `DELETE /shares/{code}` shipped in 0.1.4 sending no such header, so
/// adding one now would change the bytes of an already-published surface for no gain. A caller
/// who supplies their own key on any method still has it forwarded untouched.
const IDEMPOTENT_METHODS: [&str; 3] = ["POST", "PUT", "PATCH"];

/// The most pages [`CredenShare::for_each_share`] will walk before giving up.
///
/// A bound exists because the end of the result set is not always knowable: a server that
/// omits both `total_pages` and `total` and returns full pages forever cannot be told from a
/// very large account. An unbounded walk against one hangs the caller's process and re-feeds
/// the visitor the same rows; a bounded one fails with a message naming the cause.
///
/// At the default page size of 100 this is ten million shares.
pub const MAX_PAGES: u32 = 100_000;

/// Retries for network failures. Only transport errors are retried, never an HTTP status: a
/// 5xx may have committed, and this client cannot tell. A create is safe to retry because the
/// Idempotency-Key and the body are both identical on the second attempt — which is the entire
/// reason the header is mandatory.
pub const DEFAULT_MAX_RETRIES: u32 = 2;

const CREDENTIAL_PREFIX: &str = "crs_sk_live_";

/// A parsed API credential: `crs_sk_live_<keyId>.<authSecret>[.<custodySecret>]`.
///
/// The custody secret is held here but is NEVER placed in a request. It is a separate secret
/// precisely so the server cannot reconstruct the custody private key — deriving it from the
/// auth secret, which is transmitted on every call, would mean the server *could* decrypt. Not
/// that it would; that it could.
#[derive(Clone)]
pub struct Credential {
    pub key_id: String,
    auth_secret: String,
    custody_secret: Option<String>,
}

impl Credential {
    pub fn parse(raw: &str) -> Result<Self> {
        let text = raw.trim();
        if !text.starts_with(CREDENTIAL_PREFIX) {
            return Err(Error::CredentialFormat(format!(
                "a credential starts with '{CREDENTIAL_PREFIX}'; this does not look like one"
            )));
        }
        let parts: Vec<&str> = text.split('.').collect();
        if !(2..=3).contains(&parts.len()) || parts.iter().any(|p| p.is_empty()) {
            return Err(Error::CredentialFormat(format!(
                "a credential is '{CREDENTIAL_PREFIX}<keyId>.<authSecret>' with an optional \
                 '.<custodySecret>'; this has {} part(s)",
                parts.len()
            )));
        }

        // parts[0] being non-empty only proves the PREFIX is there: "crs_sk_live_.secret"
        // splits into two non-empty parts and yields an empty key id, which then goes out in
        // an Authorization header that cannot identify anything.
        let key_id = parts[0][CREDENTIAL_PREFIX.len()..].to_string();
        if key_id.is_empty() {
            return Err(Error::CredentialFormat(
                "the credential has no key id between the prefix and the first '.'".to_string(),
            ));
        }

        Ok(Self {
            key_id,
            auth_secret: parts[1].to_string(),
            custody_secret: parts.get(2).map(|s| s.to_string()),
        })
    }

    pub fn has_custody(&self) -> bool {
        self.custody_secret.is_some()
    }

    /// The two-part value sent in the Authorization header.
    ///
    /// Assembled from the parts rather than by trimming the original string, so a third part
    /// cannot survive a formatting mistake and reach the wire.
    fn bearer(&self) -> String {
        format!("{CREDENTIAL_PREFIX}{}.{}", self.key_id, self.auth_secret)
    }

    /// The base64url custody public key to register for account custody.
    ///
    /// Only the public half leaves this machine. Any machine holding the credential derives the
    /// same keypair, so ephemeral runners need no local state.
    pub fn custody_public_key(&self) -> Result<String> {
        let secret = self.custody_secret.as_deref().ok_or_else(|| {
            Error::CredentialFormat(
                "this credential has no custody secret, so no custody keypair exists".into(),
            )
        })?;
        Ok(crypto::custody_keypair(secret)?.public_key_b64url())
    }
}

impl fmt::Debug for Credential {
    /// Never render the secrets. A credential in a log line is a credential that has to be
    /// rotated, and `#[derive(Debug)]` is how that usually happens.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "<Credential {} ({})>",
            self.key_id,
            if self.has_custody() {
                "with custody"
            } else {
                "no custody"
            }
        )
    }
}

impl fmt::Display for Credential {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        fmt::Debug::fmt(self, f)
    }
}

/// A created share, and the only place its link exists.
pub struct Share {
    pub short_code: String,
    /// The full recipient link, INCLUDING the key fragment. Treat this as the secret itself:
    /// anyone holding it can read the content, and CredenShare cannot.
    pub link: String,
    /// The content key, if you need to build your own link or decrypt later.
    pub content_key: [u8; 32],
    pub expired_at: Option<String>,
    pub custody: Option<String>,
}

impl fmt::Debug for Share {
    /// The link carries the key, so it is not printed by default.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "<Share {} (link withheld)>", self.short_code)
    }
}

/// Metadata for a share. Never content, and never a key.
///
/// Deliberately thin, because the API is: `/v1` returns the short code and the expiry and
/// nothing else. There is no title here even though you supply one on create — the server does
/// not return it, and a field that is always `None` reads as broken rather than absent.
#[derive(Debug, Clone)]
pub struct ShareSummary {
    pub short_code: String,
    pub expired_at: Option<String>,
}

/// One page of shares, with the paging figures attached.
///
/// A bare `Vec` would leave a caller guessing whether more exists, and a caller who has to
/// guess guesses wrong — usually by stopping at the first short page.
#[derive(Debug, Clone)]
pub struct SharePage {
    pub shares: Vec<ShareSummary>,
    pub page: u32,
    pub limit: u32,
    pub total: Option<u32>,
    pub total_pages: Option<u32>,
}

impl SharePage {
    /// Whether another page exists.
    ///
    /// Falls back deliberately rather than answering `false` when the server omits the paging
    /// figures: reporting "no more" on a full page is what makes [`CredenShare::for_each_share`]
    /// stop after page one and return a fraction of the account as though it were all of it.
    pub fn has_more(&self) -> bool {
        page_has_more(
            self.page,
            self.limit,
            self.total,
            self.total_pages,
            self.shares.len(),
        )
    }
}

/// A share to create.
#[derive(Debug, Default)]
pub struct CreateParams {
    pub title: String,
    pub fields: Vec<Field>,
    pub description: Option<String>,
    pub passcode: Option<String>,
    pub expired_at: Option<String>,
    pub access_counts_left: Option<u32>,
    pub timed_view: Option<u32>,

    /// Generated per call unless you set it. Setting your own does NOT make a second call a
    /// no-op: encryption is randomised per call, so the body differs and the API refuses with
    /// [`Error::IdempotencyConflict`]. That is the header working, not failing. What it
    /// protects is a network retry, which this client performs itself.
    pub idempotency_key: Option<String>,

    /// Create a share under a key you already hold — a link you handed out before the create,
    /// or a fixed key in a test. It does not make the request body reproducible.
    pub content_key: Option<[u8; 32]>,
}

/// One prompt on a collect form.
///
/// `item` is the VISIBLE PROMPT — the request-side counterpart of a share field's
/// [`Field::key`], and the same trap if you reach for `label`. `field_type` decides how the
/// prompt renders for the submitter and takes the same vocabulary as a share field's type;
/// left empty it is omitted from the request, so the API applies its own default of `text`
/// rather than being handed an empty string.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct RequestField {
    pub item: String,
    pub field_type: String,
}

impl RequestField {
    /// A prompt with an explicit type.
    pub fn new(item: impl Into<String>, field_type: impl Into<String>) -> Self {
        Self {
            item: item.into(),
            field_type: field_type.into(),
        }
    }

    /// A prompt rendered as one line of text, which is what most of them are.
    pub fn text(item: impl Into<String>) -> Self {
        Self::new(item, "text")
    }
}

/// A secure request to create.
///
/// [`Debug`] is hand-written and withholds [`Self::seed`]. The derived one printed it, which
/// meant a `dbg!(&params)` or a `tracing` field wrote the private key of every submission that
/// request will ever collect into a log — and unlike a credential, a leaked seed cannot be
/// rotated: rotating it would make the submissions already collected unreadable.
#[derive(Default)]
pub struct CreateRequestParams {
    pub title: String,

    /// What the person filling the link is asked for. At least one, and refused locally
    /// otherwise: a request with no fields is created successfully, returns a short code, and
    /// renders "Unable to Load Request" for whoever you send it to.
    pub fields: Vec<RequestField>,

    pub description: Option<String>,

    /// A password on the collect FORM, and the one secret in this crate that is transmitted.
    ///
    /// Unlike a share's passcode it is not mixed into any key derivation — the server decides
    /// who may see the form, so it has to be able to evaluate this. It gates access to the
    /// form and never the submissions: those are sealed to your public key, and this passcode
    /// cannot open one. Do not reuse a share passcode here.
    pub passcode: Option<String>,

    /// Defaults to **30 days** from now, applied by the API. Omitting it does not create a
    /// collect link that stays open forever.
    pub expired_at: Option<String>,

    /// How many submissions the link accepts in total.
    pub max_submission: Option<u32>,

    /// How many times the link may be opened.
    pub access_counts_left: Option<u32>,

    pub requires_login: Option<bool>,
    pub requires_mfa: Option<bool>,

    /// Email domains permitted to submit. Empty means no restriction.
    pub restricted_domain: Vec<String>,

    /// Addresses permitted to submit. Empty means no restriction.
    pub ip_whitelist: Vec<String>,

    /// Create the request under a team you belong to, rather than under yourself.
    ///
    /// Accepted only where it matches the organization the credential already acts in — the
    /// API refuses another team's id rather than silently creating the request under yours, so
    /// this selects among what the credential can already reach and never widens it.
    ///
    /// New in 0.2.0 alongside `create_request` itself, so it breaks nothing. There is
    /// deliberately no counterpart on [`CreateParams`]: that struct shipped in 0.1.4 without
    /// one, and adding a member to it would stop an exhaustive struct literal from compiling
    /// — a source break, which a minor release does not get to make. A share created under a
    /// team goes through [`CredenShare::request`] until the next major.
    pub organization_id: Option<String>,

    /// Generated per call unless you set it. Setting your own does NOT make a second call a
    /// no-op — the API refuses a replayed key carrying a different body with
    /// [`Error::IdempotencyConflict`], and a second `create_request` differs in at least its
    /// public key. What it protects is a network retry, which this client performs itself.
    pub idempotency_key: Option<String>,

    /// Derive the keypair from a seed you already hold instead of a fresh random one.
    ///
    /// The custody case: `custody_keypair(secret).seed()` gives an ephemeral runner a
    /// REPRODUCIBLE keypair, so a container that will not exist tomorrow can create a request
    /// today and its replacement can open the submissions with nothing stored anywhere. A
    /// fresh seed per request is the better default everywhere else, because it bounds what
    /// one leaked seed opens to one request.
    pub seed: Option<[u8; 32]>,
}

impl fmt::Debug for CreateRequestParams {
    /// Every field except the seed, which is rendered as its absence or its presence and
    /// never as its bytes.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("CreateRequestParams")
            .field("title", &self.title)
            .field("fields", &self.fields)
            .field("description", &self.description)
            .field("passcode", &self.passcode)
            .field("expired_at", &self.expired_at)
            .field("max_submission", &self.max_submission)
            .field("access_counts_left", &self.access_counts_left)
            .field("requires_login", &self.requires_login)
            .field("requires_mfa", &self.requires_mfa)
            .field("restricted_domain", &self.restricted_domain)
            .field("ip_whitelist", &self.ip_whitelist)
            .field("organization_id", &self.organization_id)
            .field("idempotency_key", &self.idempotency_key)
            .field("seed", &self.seed.as_ref().map(|_| Withheld))
            .finish()
    }
}

/// Stands in for key material in a [`fmt::Debug`] rendering.
///
/// A unit struct rather than a string so the alternate form `{:#?}` prints
/// `seed: Some(<32 bytes withheld>)` without quotes around it, which reads as a redaction
/// rather than as a value somebody chose.
struct Withheld;

impl fmt::Debug for Withheld {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("<32 bytes withheld>")
    }
}

/// A created secure request, and the only place its seed exists.
///
/// The struct's own copy of the seed is zeroized when this value drops. That is the copy, not
/// every copy: `[u8; 32]` is `Copy`, so anything you took out with `*request.seed()` — or the
/// [`Self::access_link`] string, which carries the same 32 bytes in base64url — is yours to
/// wipe. Store one of them before this value drops; nothing else in the world holds the seed.
pub struct SecureRequest {
    pub short_code: String,

    /// The collect link to hand out. Unlike a share link it carries NO key, so it is safe to
    /// publish: holding it lets somebody SUBMIT, never read.
    pub collect_link: String,

    /// YOUR link, with the seed in the fragment. Treat it as the secret itself: anyone holding
    /// it can read every submission, and CredenShare cannot rebuild it because the seed was
    /// never ours.
    ///
    /// The whole seed in one string, which is what makes it the convenient thing to paste into
    /// a secrets manager — and the reason it is withheld from this type's [`Debug`] alongside
    /// the seed itself.
    pub access_link: String,

    /// The public half, echoed back by the API so you can confirm what was stored.
    pub public_key: String,

    pub expired_at: Option<String>,

    seed: Zeroizing<[u8; 32]>,
}

impl SecureRequest {
    /// The 32-byte seed, which is the ONLY way to read this request's submissions.
    ///
    /// It was generated on this machine and never sent — the API received the public half
    /// alone, which is what makes a submission unreadable to CredenShare and to every other
    /// submitter. Store it as you would any private key: a request whose seed is lost goes on
    /// collecting submissions that nobody, including us, can ever open.
    ///
    /// A method rather than a field so that reaching for private key material is a deliberate
    /// act that shows up in a review, as it is on [`crate::SeedKeypair`].
    pub fn seed(&self) -> &[u8; 32] {
        &self.seed
    }
}

impl fmt::Debug for SecureRequest {
    /// Never render the seed, and never the access link that carries it. A seed in a log line
    /// cannot be rotated the way a credential can: every submission already collected under it
    /// would become unreadable.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "<SecureRequest {} (seed and access link withheld)>",
            self.short_code
        )
    }
}

/// Metadata for a secure request. Never a submission, and never a seed.
#[derive(Debug, Clone)]
pub struct RequestSummary {
    pub short_code: String,
    pub expired_at: Option<String>,

    /// The public half supplied on create, returned so you can confirm what was stored.
    ///
    /// `None` for a legacy request created without one — a request whose submissions cannot be
    /// sealed to anybody — and also for one of your own that has expired, which the API
    /// reports as a bare short code rather than as a 404.
    pub public_key: Option<String>,
}

/// One page of secure requests, with the paging figures attached.
#[derive(Debug, Clone)]
pub struct RequestPage {
    pub requests: Vec<RequestSummary>,
    pub page: u32,
    pub limit: u32,
    pub total: Option<u32>,
    pub total_pages: Option<u32>,
}

impl RequestPage {
    /// Whether another page exists.
    ///
    /// Answered exactly as [`SharePage::has_more`] answers it, fallback included, because the
    /// two lists are paginated identically and a divergence between them would be silent.
    pub fn has_more(&self) -> bool {
        page_has_more(
            self.page,
            self.limit,
            self.total,
            self.total_pages,
            self.requests.len(),
        )
    }
}

/// What a [`CredenShare::delete_request`] call did.
///
/// The endpoint is two-step by design, so `outcome` answers a question the caller cannot work
/// out locally. It is a string rather than an enum for the same reason [`Share::custody`] is
/// one: a value this version has not heard of must not become an error on the path whose whole
/// job is reporting what happened.
#[derive(Debug, Clone)]
pub struct RequestDeletion {
    pub short_code: String,

    /// `"expired"` — it was active, new submissions have stopped, and the ones already
    /// received are preserved — or `"deleted"`, meaning it was already expired and is now
    /// gone.
    pub outcome: Option<String>,
}

/// One sealed submission: the blob, not its contents.
///
/// Exactly the four members the handler emits — `short_code`, `created_at`, `data` and
/// `encryption_type` — and no `expired_at`. A submission has no expiry of its own: the REQUEST
/// expires, and expiring it stops new submissions rather than dating the ones already
/// collected. A member the API never populates reads as a broken field rather than an absent
/// one, so there is none, here as in the Node, Python and Go clients.
#[derive(Debug, Clone)]
pub struct Submission {
    pub short_code: String,
    pub created_at: Option<String>,

    /// The sealed submission, **padded standard base64** — not the unpadded base64url the
    /// request's public key travelled as. Pass it to [`Self::decrypt`] verbatim.
    pub data: String,

    pub encryption_type: Option<String>,
}

impl Submission {
    /// Open this submission with the seed kept when the request was created.
    ///
    /// Sealed blobs are handed back and opened on request rather than decrypted on arrival,
    /// for the same reason [`crate::decrypt_content`] is a separate call from
    /// [`CredenShare::list_shares`]: the seed belongs to the caller, and a list that decrypted
    /// silently would demand it on every read — including the reads that only want to know how
    /// many arrived.
    pub fn decrypt(&self, seed: &[u8]) -> Result<Vec<Field>> {
        crypto::decrypt_submission(&self.data, seed)
    }
}

/// Every submission to one request, in the one response the API answers with.
///
/// Not paginated, and carrying no paging figures for that reason: the endpoint returns the
/// whole set and reads neither `page` nor `limit`. `openapi.yaml` agrees — it documents no
/// `pagination` block on this response, and an earlier revision that did has been corrected.
/// Members read from figures that never arrive are how a walk asks for a page two that does
/// not exist and is handed page one again; a member that is always absent reads as a broken
/// field rather than an absent one, so there is none.
#[derive(Debug, Clone)]
pub struct SubmissionPage {
    pub submissions: Vec<Submission>,

    /// How many rows the API reports in this response, where it reports a count.
    ///
    /// The API's own figure, alongside the rows rather than instead of them: it counts what
    /// the response contains, so a mismatch with `submissions.len()` is worth investigating
    /// rather than papering over.
    pub count: Option<u32>,

    /// How many submissions the API WITHHELD because they are not end-to-end encrypted.
    ///
    /// A request created before client-side encryption, or without a public key, collects
    /// submissions the server can read — and it refuses to hand those to a credential rather
    /// than make this the one endpoint where a bearer token yields readable secrets. They are
    /// counted rather than silently dropped, so a reconciliation against your dashboard does
    /// not report submissions as missing when they are merely unreadable this way.
    ///
    /// Every request this crate creates carries a public key, so its own requests never
    /// produce one.
    pub skipped_not_end_to_end_encrypted: Option<u32>,
}

/// Usage figures for the account — or for the TEAM, when the credential acts in one.
///
/// The per-member breakdown the dashboard shows is deliberately absent from the API: a
